router.post('/browser/:sessionId', async (req, res) => {
  const session = sessions.get(req.params.sessionId);
  if (!session) return res.status(410).json({ message: 'Phiên đăng nhập đã hết hạn.' });
  if (req.get('origin') !== session.origin) {
    return res.status(403).json({ message: 'Nguồn yêu cầu đăng nhập không hợp lệ.' });
  }
  const idToken = req.body?.idToken;
  if (typeof idToken !== 'string' || !idToken || idToken.length > 10000) {
    return res.status(400).json({ message: 'Google ID token không hợp lệ.' });
  }
  if (session.verifying || session.idToken) {
    return res.status(409).json({ message: 'Phiên này đã nhận kết quả đăng nhập.' });
  }
  session.verifying = true;
  try {
    const ticket = await client.verifyIdToken({ idToken, audience: session.audience });
    const profile = ticket.getPayload();
    if (!profile?.sub || !profile.email_verified || !profile.email || profile.nonce !== session.nonce) {
      throw new Error('Invalid Google identity or nonce');
    }
    if (session.expiresAt <= Date.now() || sessions.get(req.params.sessionId) !== session) {
      return res.status(410).json({ message: 'Phiên đăng nhập đã hết hạn.' });
    }
    session.idToken = idToken;
    return res.json({ success: true });
  } catch {
    return res.status(401).json({ message: 'Không xác minh được tài khoản Google. Hãy thử lại.' });
  } finally {
    session.verifying = false;
  }
});

router.post('/result', (req, res) => {
  const { sessionId, secret } = req.body || {};
  const session = sessions.get(sessionId);
  if (!session || typeof secret !== 'string' || secret.length !== 64 ||
      !timingSafeEqual(session.secretHash, createHash('sha256').update(secret).digest())) {
    return res.status(410).json({ success: false, message: 'Phiên đăng nhập không hợp lệ hoặc đã hết hạn.' });
  }
  if (!session.idToken) {
    sessions.delete(sessionId);
    return res.status(400).json({ success: false, message: 'Bạn chưa hoàn tất đăng nhập Google. Hãy thử lại và chọn tài khoản trước khi nhấn Xong.' });
  }
  sessions.delete(sessionId);
  return res.json({ success: true, idToken: session.idToken });
});

module.exports = router;
