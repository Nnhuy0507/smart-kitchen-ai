const express = require('express');
const { randomBytes, createHash, timingSafeEqual } = require('node:crypto');
const { OAuth2Client } = require('google-auth-library');

const router = express.Router();
const client = new OAuth2Client();
const sessions = new Map();
const SESSION_DURATION = 5 * 60 * 1000;

function removeExpiredSessions() {
  for (const [id, session] of sessions) {
    if (session.expiresAt <= Date.now()) sessions.delete(id);
  }
}

function browserOrigin() {
  const url = new URL(process.env.GOOGLE_EXPO_WEB_ORIGIN || '');
  if (url.protocol !== 'https:' || url.username || url.password ||
      url.pathname !== '/' || url.search || url.hash) {
    throw new Error('Invalid Google browser origin');
  }
  return url.origin;
}

router.use((req, res, next) => {
  removeExpiredSessions();
  res.set('Cache-Control', 'no-store');
  res.set('Referrer-Policy', 'no-referrer');
  next();
});

router.post('/session', (req, res) => {
  let origin;
  try {
    origin = browserOrigin();
    if (!process.env.GOOGLE_WEB_CLIENT_ID?.trim()) throw new Error('Missing client ID');
  } catch {
    return res.status(503).json({
      success: false,
      message: 'Đăng nhập Google trong Expo Go cần GOOGLE_EXPO_WEB_ORIGIN là địa chỉ HTTPS của backend. Thêm origin này vào Authorized JavaScript origins của Google OAuth Web Client.',
    });
  }
  if (sessions.size >= 500) {
    return res.status(429).json({ success: false, message: 'Có quá nhiều phiên đăng nhập. Hãy thử lại sau.' });
  }
  const sessionId = randomBytes(32).toString('hex');
  const secret = randomBytes(32).toString('hex');
  const expiresAt = Date.now() + SESSION_DURATION;
  sessions.set(sessionId, {
    secretHash: createHash('sha256').update(secret).digest(),
    nonce: randomBytes(32).toString('hex'),
    audience: process.env.GOOGLE_WEB_CLIENT_ID.trim(),
    origin,
    expiresAt,
    verifying: false,
    idToken: null,
  });
  return res.json({
    success: true,
    sessionId,
    secret,
    browserUrl: `${origin}/api/auth/google/expo/browser/${sessionId}`,
  });
});

